#!/usr/bin/env bash
# Generate embed declarations after building or restoring sandbox assets.
# Keep optional go:embed patterns out of tracked Go files: go mod vendor scans
# all build tags, even when sandbox_embed is not enabled.
set -euo pipefail

ARCH="${1:-$(go env GOARCH)}"
case "$ARCH" in
  arm64|amd64) ;;
  *) echo "unsupported arch: $ARCH (want arm64|amd64)" >&2; exit 1 ;;
esac
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/pkg/sandbox"
for asset in bwrap python-base.tar.gz n9e-sandbox-init; do
  if [ ! -s "$OUT/embedassets/linux_$ARCH/$asset" ]; then
    echo "missing sandbox asset: $OUT/embedassets/linux_$ARCH/$asset; run scripts/build-sandbox-assets.sh $ARCH first" >&2
    exit 1
  fi
done

EMBED_SOURCE_TMP="$(mktemp "$OUT/.embed-assets.XXXXXX")"
trap 'rm -f "$EMBED_SOURCE_TMP"' EXIT
cat > "$EMBED_SOURCE_TMP" <<EOF
// Code generated by scripts/generate-sandbox-embed.sh; DO NOT EDIT.

//go:build sandbox_embed && linux && $ARCH

package sandbox

import _ "embed"

//go:embed embedassets/linux_$ARCH/bwrap
var bwrapBin []byte

//go:embed embedassets/linux_$ARCH/python-base.tar.gz
var baseTarGz []byte

//go:embed embedassets/linux_$ARCH/n9e-sandbox-init
var initBin []byte
EOF
chmod 0644 "$EMBED_SOURCE_TMP"
mv "$EMBED_SOURCE_TMP" "$OUT/embed_assets_generated_linux_$ARCH.go"
